"""Tests for PullRequestManager — PR body construction and label generation."""
import pytest

from automaintainer.github.pr_manager import PullRequestManager, _ATTRIBUTION
from automaintainer.core.models import RiskTier
from automaintainer.inference.schemas import PlannerOutput, ProposedEdit, ValidationStep
from automaintainer.validation.runner import ValidationReport, GateResult


def _make_plan(task_type: str = "github_action_update") -> PlannerOutput:
    return PlannerOutput(
        objective="Update outdated GitHub Actions",
        task_type=task_type,
        confidence=0.95,
        target_paths=[".github/workflows/ci.yml"],
        proposed_edits=[
            ProposedEdit(
                path=".github/workflows/ci.yml",
                operation="regex_replace",
                rationale="Bump actions/checkout from v2 to v4",
            )
        ],
        explicitly_unchanged=[],
        validation_steps=[
            ValidationStep(command="yamllint .", reason="lint", expected_outcome="ok")
        ],
        risk_tier=RiskTier.R1,
        requires_human_approval=False,
    )


def _make_validation_report(passed: bool = True) -> ValidationReport:
    return ValidationReport(
        session_id="sess_abc",
        passed=passed,
        is_safety_stop=False,
        gate_results=[
            GateResult(gate_name="syntax", passed=True),
            GateResult(gate_name="secret_scan", passed=True),
            GateResult(gate_name="diff_firewall", passed=passed),
        ],
        summary="All gates passed" if passed else "diff_firewall failed",
    )


manager = PullRequestManager()


def test_pr_title_for_actions_update():
    plan = _make_plan("github_action_update")
    title = manager.build_pr_title(plan)
    assert "GitHub Actions" in title
    assert title.startswith("chore:")


def test_pr_title_for_docs_link_fix():
    plan = _make_plan("docs_link_fix")
    title = manager.build_pr_title(plan)
    assert "docs" in title.lower() or "link" in title.lower()


def test_pr_body_contains_required_sections():
    plan = _make_plan()
    report = _make_validation_report()
    body = manager.build_pr_body("sess_abc123", plan, report, "owner/repo", RiskTier.R1)

    assert "## AutoMaintainer" in body
    assert "sess_abc123" in body
    assert "What was found" in body
    assert "What changed" in body
    assert "Why this is safe" in body
    assert "Validation checklist" in body
    assert "Session metadata" in body


def test_pr_body_contains_attribution_once():
    plan = _make_plan()
    report = _make_validation_report()
    body = manager.build_pr_body("sess_abc123", plan, report, "owner/repo", RiskTier.R1)

    count = body.count("AutoMaintainer")
    assert count >= 1  # At least in header and attribution
    assert "autonomous maintenance bot" in body


def test_pr_body_shows_risk_tier():
    plan = _make_plan()
    report = _make_validation_report()
    body = manager.build_pr_body("sess_test", plan, report, "owner/repo", RiskTier.R2)

    assert "R2" in body


def test_pr_labels_include_required_labels():
    plan = _make_plan("github_action_update")
    labels = manager.build_pr_labels(plan, "sess_x", RiskTier.R1)

    assert "automaintainer" in labels
    assert "maintenance" in labels
    assert "autogenerated" in labels
    assert any("risk:" in l for l in labels)
    assert any("github" in l.lower() or "action" in l.lower() for l in labels)


def test_pr_labels_reflect_risk_tier():
    plan = _make_plan()
    labels_r1 = manager.build_pr_labels(plan, "sess_x", RiskTier.R1)
    labels_r2 = manager.build_pr_labels(plan, "sess_x", RiskTier.R2)

    assert "risk:r1" in labels_r1
    assert "risk:r2" in labels_r2


@pytest.mark.asyncio
async def test_pr_lookup_fails_closed_on_http_500():
    from unittest.mock import AsyncMock, MagicMock
    from automaintainer.github.pr_manager import PRLookupError
    import httpx

    mock_executor = MagicMock()
    mock_executor.api_base_url = "https://api.github.com"
    
    async def _send_req(*args, **kwargs):
        return httpx.Response(500, text="Internal Server Error")
    mock_executor._send_request = _send_req

    pr_mgr = PullRequestManager(executor=mock_executor)
    with pytest.raises(PRLookupError, match="HTTP 500"):
        await pr_mgr._lookup_existing_pr("owner", "repo", "patch-branch")


