@pytest.mark.asyncio
async def test_pr_creation_distributed_reservation_barrier():
    from unittest.mock import MagicMock
    from automaintainer.github.pr_manager import PRCreationReservationBarrier

    mock_redis = MagicMock()
    mock_redis.set.side_effect = [True, False]
    mock_redis.eval.return_value = 1

    tok1 = await PRCreationReservationBarrier.acquire_reservation("owner/repo:patch", redis_client=mock_redis)
    assert tok1 != ""

    tok2 = await PRCreationReservationBarrier.acquire_reservation("owner/repo:patch", redis_client=mock_redis)
    assert tok2 == ""

    released = await PRCreationReservationBarrier.release_reservation("owner/repo:patch", tok1, redis_client=mock_redis)
    assert released is True
